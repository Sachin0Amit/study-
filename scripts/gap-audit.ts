/**
 * Master-Syllabus Gap Audit — the mechanical gap list for the Full-Library
 * Gap-Fill Authoring Program (docs/syllabus/MASTER-SYLLABUS.md).
 *
 * Reads the serialized registries (knowledge-meta.json) + live section
 * content (public/data/content.json) and reports, per subject:
 *   - chapters declared vs chapters with lessons
 *   - lessons per chapter
 *   - lessons below the 2,000-word depth bar (readingTime × 200 estimate)
 *   - quizzes below 6 items
 *   - lessons with fewer than 4 concepts
 *
 * Usage:
 *   bun run scripts/gap-audit.ts                 → full report to coverage/GAP-AUDIT.md
 *   bun run scripts/gap-audit.ts --subject <id>  → single-subject detail to stdout
 */
import { readFileSync, writeFileSync } from 'fs'

const meta = JSON.parse(readFileSync('src/data/library-parts/knowledge-meta.json', 'utf8'))
const content = JSON.parse(readFileSync('public/data/content.json', 'utf8'))
const bySection = new Map(content.map((c: any) => [c.sectionId, c]))

const onlyArg = process.argv.indexOf('--subject')
const only = onlyArg > -1 ? process.argv[onlyArg + 1] : null

interface LessonStat {
  id: string
  title: string
  chapter: string
  estWords: number
  quiz: number
  concepts: number
}

const lines: string[] = []
const detail = (msg: string) => {
  if (only) console.log(msg)
  else lines.push(msg)
}

const subjects = meta.subjects.filter((s: any) => s.id.startsWith('ku-'))

let totalBooks = 0
let flaggedBooks = 0
const summary: string[] = []

for (const subj of subjects) {
  if (only && subj.id !== only) continue
  const book = meta.books.find((b: any) => b.subjectId === subj.id)
  const chapters = meta.chapters.filter((c: any) => c.bookId === (book?.id ?? subj.id))
  const lessons: LessonStat[] = []
  const emptyChapters: string[] = []
  for (const ch of chapters) {
    const secs = meta.sections.filter((s: any) => s.chapterId === ch.id)
    if (secs.length === 0) emptyChapters.push(`Ch${ch.number} ${ch.title}`)
    for (const sec of secs) {
      const c = bySection.get(sec.id)
      lessons.push({
        id: sec.id,
        title: sec.title,
        chapter: `Ch${ch.number}`,
        estWords: (c?.readingTime ?? 0) * 200,
        quiz: c?.quiz?.length ?? 0,
        concepts: c?.concepts?.length ?? 0,
      })
    }
  }
  const thin = lessons.filter((l) => l.estWords < 2000)
  const quizPoor = lessons.filter((l) => l.quiz < 6)
  const flagged = emptyChapters.length > 0 || thin.length > 0 || quizPoor.length > 0 || lessons.length < 3
  totalBooks++
  if (flagged) flaggedBooks++

  detail(`\n## ${subj.id} — ${subj.name}`)
  detail(`chapters: ${chapters.length} · lessons: ${lessons.length} · est-words total: ${lessons.reduce((a, l) => a + l.estWords, 0).toLocaleString()}`)
  if (emptyChapters.length) detail(`EMPTY CHAPTERS: ${emptyChapters.join(' | ')}`)
  if (thin.length) detail(`below-2000w (${thin.length}): ${thin.map((l) => `${l.id.replace('ku-', '')}≈${l.estWords}w`).join(', ')}`)
  if (quizPoor.length) detail(`quiz<6 (${quizPoor.length}): ${quizPoor.map((l) => `${l.id.replace('ku-', '')} q${l.quiz}`).join(', ')}`)
  if (!flagged) detail('STATE: at-bar ✓')

  if (!only) {
    summary.push(
      `${flagged ? '⬜' : '✓'} ${subj.id.padEnd(38)} ${String(chapters.length).padStart(2)}ch ${String(lessons.length).padStart(3)}ls  thin:${String(thin.length).padStart(3)} quiz<6:${String(quizPoor.length).padStart(3)}${emptyChapters.length ? ' EMPTY-CH:' + emptyChapters.length : ''}`,
    )
  }
}

if (!only) {
  const out = `# Gap Audit — ${new Date().toISOString().slice(0, 10)} (auto-generated by scripts/gap-audit.ts)

Program reference: docs/syllabus/MASTER-SYLLABUS.md
Bar: every lesson ≥2,000 words (est = readingTime×200), quiz ≥6, ≥3 lessons/book, no empty chapters.

## Summary — ${totalBooks} ku-subjects, ${flaggedBooks} flagged

\`\`\`
${summary.join('\n')}
\`\`\`

## Detail

${lines.join('\n')}
`
  writeFileSync('coverage/GAP-AUDIT.md', out)
  console.log(`gap audit written — ${totalBooks} subjects, ${flaggedBooks} flagged → coverage/GAP-AUDIT.md`)
}
